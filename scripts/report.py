#!/usr/bin/env python3
"""Turn the retained evidence JSON into one readable markdown report.

Defensive by design: every section is optional, so a partially failed lane still
produces a truthful report instead of crashing the run.
"""
import json
import os
import subprocess
from pathlib import Path

R = Path("reports")
OUT = R / "report.md"
lines = []


def h(level, text):
    lines.append(f"{'#' * level} {text}\n")


def code(text, lang=""):
    lines.append(f"```{lang}\n{text.strip()}\n```\n")


def load(name):
    p = R / name
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None


def walk(obj, *keys):
    """Return the first value found for any of the keys, depth-first."""
    stack = [obj]
    seen = 0
    while stack and seen < 200000:
        seen += 1
        cur = stack.pop()
        if isinstance(cur, dict):
            for k in keys:
                if k in cur and not isinstance(cur[k], (dict, list)):
                    return cur[k]
            stack.extend(reversed(list(cur.values())))
        elif isinstance(cur, list):
            stack.extend(reversed(cur))
    return None


def collect(obj, key, limit=80):
    """Collect all values for `key` anywhere in the tree."""
    out, stack, seen = [], [obj], 0
    while stack and len(out) < limit and seen < 200000:
        seen += 1
        cur = stack.pop()
        if isinstance(cur, dict):
            if key in cur and not isinstance(cur[key], (dict, list)):
                out.append(cur[key])
            stack.extend(reversed(list(cur.values())))
        elif isinstance(cur, list):
            stack.extend(reversed(cur))
    return out


h(1, "MovieBox — reverse engineering & rebuild report")
lines.append(
    "Generated by the `MovieBox — REA analysis, rebuild & sign` workflow. "
    "Input: the APK supplied in Google Drive. Static analysis only: the app was never executed.\n"
)

# ---------------------------------------------------------------- provenance
h(2, "1. Source artifact")
src_sha = ""
for name in ("source-apk.sha256",):
    p = R / name
    if p.exists():
        src_sha = p.read_text().strip()
if src_sha:
    code(src_sha)
zt = R / "source-apk-ziptest.txt"
if zt.exists():
    lines.append(f"Archive integrity test: `{zt.read_text().strip().splitlines()[-1] if zt.read_text().strip() else 'n/a'}`\n")

# ---------------------------------------------------------------- toolchain
h(2, "2. Toolchain")
doc = load("rea-doctor.json") or {}
checks = doc.get("checks", []) if isinstance(doc, dict) else []
if checks:
    lines.append("| Check | OK | Classification | Detail |")
    lines.append("|---|---|---|---|")
    for c in checks:
        detail = str(c.get("detail", ""))[:110].replace("|", "\\|")
        lines.append(f"| {c.get('name')} | {c.get('ok')} | {c.get('classification','')} | {detail} |")
    lines.append("")
ident = doc.get("identity", {}) if isinstance(doc, dict) else {}
if ident:
    lines.append(f"REA CLI `{ident.get('cli_package_version','?')}` — "
                 f"{ident.get('catalog',{}).get('counts',{}).get('cli_commands','?')} CLI commands, "
                 f"{ident.get('catalog',{}).get('counts',{}).get('mcp_tools','?')} MCP tools.\n")

# ---------------------------------------------------------------- package
h(2, "3. Package identity (REA · JADX lane)")
pkg = load("android-package.json")
if pkg:
    fields = {
        "package": ("package", "package_name", "packageName"),
        "version name": ("version_name", "versionName"),
        "version code": ("version_code", "versionCode"),
        "min SDK": ("min_sdk", "minSdk"),
        "target SDK": ("target_sdk", "targetSdk"),
        "compile SDK": ("compile_sdk", "compileSdk"),
        "class count": ("class_count", "classes"),
        "resource count": ("resource_count",),
    }
    lines.append("| Property | Value |")
    lines.append("|---|---|")
    for label, keys in fields.items():
        v = walk(pkg, *keys)
        if isinstance(v, list):
            v = len(v)
        if v is not None:
            lines.append(f"| {label} | `{v}` |")
    lines.append("")

    perms = sorted(set(collect(pkg, "permissions", 400) + collect(pkg, "name", 400)))
    used = sorted({p for p in perms if isinstance(p, str) and p.startswith("android.permission")})
    if used:
        h(3, "Declared permissions")
        for p in used[:80]:
            lines.append(f"- `{p}`")
        lines.append("")
else:
    lines.append("_Package evidence unavailable (see `android-package.stderr`)._\n")

# ---------------------------------------------------------------- components
if pkg:
    comps = collect(pkg, "activity", 200) + collect(pkg, "service", 200)
    exported = sorted({c for c in comps if isinstance(c, str) and "." in c})
    if exported:
        h(3, "Component names observed")
        for c in exported[:40]:
            lines.append(f"- `{c}`")
        lines.append("")

# ---------------------------------------------------------------- signature
h(2, "4. Source APK signing schemes (REA)")
sig = load("apk-signature.json")
if sig:
    sch = walk(sig, "schemes", "scheme", "verified_schemes")
    if isinstance(sch, list):
        lines.append(f"Schemes detected: {', '.join(map(str, sch))}\n")
    for key in ("v1", "v2", "v3", "v3.1", "signers", "certificate_sha256", "sha256"):
        v = walk(sig, key)
        if v is not None and not isinstance(v, (dict, list)):
            lines.append(f"- `{key}`: `{v}`")
    lines.append("")
    code(json.dumps(sig, indent=2)[:3000], "json")
else:
    lines.append("_Signing evidence unavailable._\n")

# ---------------------------------------------------------------- resources
h(2, "5. Resources & manifest (REA · apktool lane)")
res = load("apktool-decode.json")
if res:
    stats = {k: walk(res, k) for k in ("package", "version", "string_count", "entry_count", "apktool_version")}
    stats = {k: v for k, v in stats.items() if v is not None}
    if stats:
        for k, v in stats.items():
            lines.append(f"- `{k}`: `{v}`")
        lines.append("")
    strings = collect(res, "value", 40)
    if strings:
        h(3, "Sample decoded strings")
        for s in strings[:25]:
            if isinstance(s, str) and s.strip():
                lines.append(f"- `{s[:120]}`")
        lines.append("")
else:
    lines.append("_apktool evidence unavailable._\n")

# ---------------------------------------------------------------- native
h(2, "6. Native code lane")
libs = R / "native-libs.txt"
if libs.exists() and libs.read_text().strip():
    code(libs.read_text()[:4000], "text")
else:
    lines.append("_No native libraries in this build._\n")

exp = load("native-exports.json")
if exp:
    names = collect(exp, "name", 60)
    if names:
        h(3, "Exported symbols (sample)")
        lines.append(", ".join(f"`{n}`" for n in names[:40]) + "\n")

gh = R / "ghidra-headless.log"
if gh.exists():
    tail = "\n".join(gh.read_text(errors="replace").splitlines()[-25:])
    h(3, "Ghidra headless log (tail)")
    code(tail, "text")
fn = Path("ghidra-functions.tsv")
for cand in (fn, R / "ghidra-functions.tsv"):
    if cand.exists():
        rows = cand.read_text(errors="replace").splitlines()
        h(3, "Ghidra function inventory")
        lines.append(f"{len(rows)} rows retained; first 20:\n")
        code("\n".join(rows[:20]), "text")
        break

# ---------------------------------------------------------------- rebuild
h(2, "7. Rebuild & signature")
mod = R / "manifest-modifications.txt"
if mod.exists():
    lines.append(mod.read_text() + "\n")

ident_file = Path("build/signing-identity.txt")
if ident_file.exists():
    code(ident_file.read_text(), "text")

art = R / "build-artifacts.sha256"
if art.exists():
    h(3, "Artifact digests")
    code(art.read_text(), "text")

diff = R / "decoded-vs-rebuilt-vs-original.txt"
if diff.exists():
    h(3, "Original vs rebuilt (smali parity)")
    code(diff.read_text()[:6000], "text")

# ---------------------------------------------------------------- verify
h(2, "8. Verification")
vl = R / "verification.log"
if vl.exists():
    code(vl.read_text(), "text")
av = R / "apksigner-verify.txt"
if av.exists():
    h(3, "apksigner verify --print-certs")
    code(av.read_text(), "text")

badg = R / "rebuilt-badging.txt"
if badg.exists():
    h(3, "Rebuilt APK badging")
    code("\n".join(badg.read_text(errors="replace").splitlines()[:12]), "text")

# ---------------------------------------------------------------- footer
h(2, "9. Limits of this analysis")
lines.append(
    "- Static only: the APK was never executed, and no device/emulator behaviour was observed.\n"
    "- JADX/Ghidra output can be partial on obfuscated or packed code; counts reflect what the engines emitted.\n"
    "- A valid signature proves the archive was signed by the key recorded above — it is not a claim about the\n"
    "  original vendor's signature, which was not reused.\n"
)

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"report written: {OUT} ({OUT.stat().st_size} bytes)")
